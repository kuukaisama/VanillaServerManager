"""新規Minecraftサーバー用の初期ファイル作成。"""

from datetime import datetime
from pathlib import Path
import shutil
import zipfile

from . import APP_DISPLAY_NAME
from .validation import validate_backup_directory


def create_server_files(profile, jar_source, properties, eula_accepted):
    """新しいサーバーディレクトリと基本設定を作成する。"""
    server_directory = profile.server_directory.resolve()
    backup_directory = profile.backup_directory.resolve()
    jar_source = Path(jar_source).resolve()

    if server_directory == backup_directory:
        raise ValueError("サーバー作成先とバックアップ保存先は分けてください。")

    validate_backup_directory(
        server_directory, backup_directory, properties.get("level-name", "world")
    )

    if not jar_source.is_file():
        raise FileNotFoundError(f"サーバーJARが見つかりません。\n{jar_source}")

    validate_server_jar(jar_source)

    if server_directory.exists() and any(server_directory.iterdir()):
        raise FileExistsError(
            "新規作成先のディレクトリが空ではありません。\n"
            f"{server_directory}"
        )

    server_directory_existed = server_directory.exists()
    backup_directory_existed = backup_directory.exists()
    created_files = []

    try:
        server_directory.mkdir(parents=True, exist_ok=True)
        backup_directory.mkdir(parents=True, exist_ok=True)

        destination_jar = server_directory / "server.jar"
        if jar_source != destination_jar:
            created_files.append(destination_jar)
            shutil.copy2(jar_source, destination_jar)

        properties_file = server_directory / "server.properties"
        created_files.append(properties_file)
        header = (
            "#Minecraft server properties\n"
            f"#{datetime.now().astimezone().strftime('%a %b %d %H:%M:%S %Z %Y')}\n"
        )
        property_lines = [
            f"{key}={_sanitize_property_value(value)}\n"
            for key, value in properties.items()
        ]
        properties_file.write_text(
            header + "".join(property_lines),
            encoding="utf-8",
            newline="",
        )
        eula_file = server_directory / "eula.txt"
        created_files.append(eula_file)
        eula_file.write_text(
            f"#Generated by {APP_DISPLAY_NAME}\n"
            f"eula={'true' if eula_accepted else 'false'}\n",
            encoding="utf-8",
            newline="",
        )
    except Exception:
        for path in reversed(created_files):
            try:
                path.unlink()
            except OSError:
                pass

        if not backup_directory_existed:
            try:
                backup_directory.rmdir()
            except OSError:
                pass
        if not server_directory_existed:
            try:
                server_directory.rmdir()
            except OSError:
                pass
        raise


def _sanitize_property_value(value):
    text = str(value)
    if "\n" in text or "\r" in text:
        raise ValueError("設定値に改行は使用できません。")
    return text


def validate_server_jar(jar_path):
    """単体起動できない内部JARを新規サーバー用として拒否する。"""
    jar_path = Path(jar_path)
    try:
        with zipfile.ZipFile(jar_path, "r") as jar_file:
            try:
                manifest = jar_file.read("META-INF/MANIFEST.MF").decode(
                    "utf-8", errors="replace"
                )
            except KeyError as error:
                raise ValueError(
                    "JARに起動情報がありません。公式サーバーJARを選択してください。"
                ) from error

            main_class = ""
            for line in manifest.splitlines():
                if line.lower().startswith("main-class:"):
                    main_class = line.split(":", 1)[1].strip()
                    break

            if not main_class:
                raise ValueError(
                    "JARにMain-Classがありません。公式サーバーJARを選択してください。"
                )

            if (
                main_class == "net.minecraft.server.Main"
                and "joptsimple/ValueConverter.class" not in jar_file.namelist()
            ):
                raise ValueError(
                    "選択したJARは公式配布JAR内部の本体ファイルで、単体では起動できません。\n"
                    "Minecraft公式サイトからダウンロードしたserver.jarを使用してください。"
                )
    except zipfile.BadZipFile as error:
        raise ValueError("有効なJARファイルではありません。") from error
